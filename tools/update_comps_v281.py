for c in N:
    c["id"] = f"c{next_id}"; next_id += 1
    c["picks"] = {k: c["picks"][k] for k in LANES}
    vals = list(c["picks"].values())
    if len(vals) != 5 or len(set(vals)) != 5: raise SystemExit(f"bad picks {c['name']} {vals}")
    for h in vals + c["core"] + c["bans"]:
        if h not in heroes: raise SystemExit(f"missing hero {h} in {c['name']}")
    if not set(c["core"]).issubset(set(vals)): raise SystemExit(f"core not subset {c['name']} {c['core']} {vals}")
    if set(c["bans"]) & set(vals): raise SystemExit(f"ban overlap {c['name']} {c['bans']} {vals}")
    if len(c["bans"]) < 4: raise SystemExit(f"not enough bans {c['name']}")

