def norm_bans(c, extra):
    picks = set(c["picks"].values())
    out=[]
    for b in list(c.get("bans",[])) + list(extra):
        if b in picks or b in out: continue
        out.append(b)
        if len(out)>=6: break
    # guarantee some depth
    if len(out)<4:
        for b in ["弈星","吕布","干将莫邪","蒙恬","哪吒","东皇太一","张良","盾山"]:
            if b not in picks and b not in out:
                out.append(b)
            if len(out)>=4: break
    return out

